import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import { createExtractionService } from "../dist/documents/service.js";
import { extractionFixture, eventually, temporary, workerConfig, workerResult } from "./documents-extract-fixture.mjs";

test("queue is asynchronous, runs one worker at a time and indexes extracted body", async t => {
  const file = join(temporary(t), "events");
  const source = `const fs=require('node:fs');fs.appendFileSync(${JSON.stringify(file)},${JSON.stringify("start\n")});setTimeout(()=>{fs.appendFileSync(${JSON.stringify(file)},${JSON.stringify("end\n")});process.stdout.write(${JSON.stringify(JSON.stringify(workerResult()))})},100)`;
  const f = extractionFixture(t, workerConfig(source));
  const rows = [f.add(), f.add({ bytes: Buffer.from("%PDF-other") }), f.add({ bytes: Buffer.from("%PDF-third") })];
  for (const row of rows) { f.enqueue(row); assert.equal(f.record(row).status, "pending"); }
  await eventually(() => f.raw.prepare("SELECT count(*) AS n FROM document_extractions WHERE status='running'").get().n === 1);
  assert.equal(f.raw.prepare("SELECT count(*) AS n FROM document_extractions WHERE status='pending'").get().n, 2);
  for (const row of rows) assert.equal((await f.completed(row)).status, "done");
  assert.equal(readFileSync(file, "utf8"), "start\nend\nstart\nend\nstart\nend\n");
  const scope = { projectId: f.projectId, teamId: null, viewer: "operator" };
  assert.equal(f.knowledge.search(scope, "searchableworkerbody").length, 3);
  assert.deepEqual(f.raw.prepare("SELECT DISTINCT body_indexed FROM knowledge_indexed").all(), [{ body_indexed: 1 }]);
});
test("queue reuses content hash only with matching converter and converter version", async t => {
  const file = join(temporary(t), "calls");
  const source = `require('node:fs').appendFileSync(${JSON.stringify(file)},'x');process.stdout.write(${JSON.stringify(JSON.stringify(workerResult()))})`;
  const f = extractionFixture(t, workerConfig(source)), first = f.add();
  f.enqueue(first); await f.completed(first);
  const second = f.add(); f.enqueue(second); await f.completed(second);
  assert.equal(readFileSync(file, "utf8"), "x");
  assert.equal(f.raw.prepare("SELECT count(DISTINCT text_hash) AS n FROM document_extractions").get().n, 1);
  f.raw.exec("UPDATE document_extractions SET converter_version='old'");
  const third = f.add(); f.enqueue(third); await f.completed(third); assert.equal(readFileSync(file, "utf8"), "xx");
});
test("startup recovery requeues pending/running rows and backfills missing versions", async t => {
  const f = extractionFixture(t); const rows = [f.add(), f.add(), f.add({ mediaType: "text/plain", bytes: Buffer.alloc(0) })];
  f.enqueue(rows[0]); f.enqueue(rows[1]); await f.service.close();
  f.raw.prepare("UPDATE document_extractions SET status='running' WHERE artifact_id=?").run(rows[1].artifactId);
  const recovered = createExtractionService({ ...f, config: workerConfig() });
  f.app.addHook("onClose", () => recovered.close()); recovered.recover();
  for (const row of rows) assert.equal(recovered.get(row.projectId, row.artifactId, 1).status, "pending");
  await eventually(() => f.raw.prepare("SELECT count(*) AS n FROM document_extractions WHERE status='done'").get().n === 3);
});
test("failed extraction permits exactly three retries and no duplicate enqueue resets attempts", async t => {
  const f = extractionFixture(t, workerConfig('process.stdout.write(JSON.stringify({error:"corrupt"}));process.exitCode=1')), row = f.add();
  f.enqueue(row); assert.equal((await f.completed(row)).errorCode, "corrupt");
  for (let i = 0; i < 3; i++) { assert.equal(f.service.retry(row.projectId, row.artifactId, 1), true); await f.completed(row); }
  assert.equal(f.service.retry(row.projectId, row.artifactId, 1), false);
  f.enqueue(row); assert.equal(f.raw.prepare("SELECT attempts FROM document_extractions").get().attempts, 4);
});
for (const [mediaType, config, code] of [
  ["image/png", workerConfig(), "not-text"], ["image/svg+xml", workerConfig(), "not-text"],
  ["application/pdf", { enabled: true, python: "missing", script: "missing" }, "worker-unavailable"],
  ["application/pdf", { ...workerConfig(), enabled: false }, "worker-disabled"],
]) test(`queue skips ${mediaType}: ${code}`, async t => {
  const f = extractionFixture(t, config), row = f.add({ mediaType }); f.enqueue(row);
  const result = await f.completed(row); assert.equal(result.status, "skipped"); assert.equal(result.errorCode, code);
  assert.equal(f.service.retry(row.projectId, row.artifactId, 1), code === "worker-unavailable");
});
test("queue stores Markdown within content store ceiling and indexes only first 200000 chars", async t => {
  const markdown = "indexprefix " + " ".repeat(200000) + "indexsuffix";
  // Large JSON is generated by the child, keeping the command below Windows' command-line limit.
  const source = `const result=${JSON.stringify(workerResult())};result.markdown='indexprefix '+' '.repeat(200000)+'indexsuffix';process.stdout.write(JSON.stringify(result))`;
  const f = extractionFixture(t, workerConfig(source)), row = f.add(); f.enqueue(row); await f.completed(row);
  assert.equal(f.service.text(row.projectId, row.artifactId, 1), markdown);
  const scope = { projectId: f.projectId, teamId: null, viewer: "operator" };
  assert.equal(f.knowledge.search(scope, "indexprefix").length, 1); assert.equal(f.knowledge.search(scope, "indexsuffix").length, 0);
  f.store.maxObjectBytes = 9;
  const small = f.add({ mediaType: "text/plain", bytes: Buffer.from("éééééé") }); f.enqueue(small); await f.completed(small);
  assert.equal(f.service.text(small.projectId, small.artifactId, 1), "éééé");
  assert.deepEqual(JSON.parse(f.raw.prepare("SELECT warnings_json FROM document_extractions WHERE artifact_id=?").get(small.artifactId).warnings_json), ["truncated-text"]);
});
