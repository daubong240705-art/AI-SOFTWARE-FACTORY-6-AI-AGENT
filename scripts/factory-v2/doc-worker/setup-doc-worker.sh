#!/bin/bash
# Creates the Python environment of the document worker (MarkItDown) under ~/factory-v2/doc-worker/venv.
#   bash scripts/factory-v2/doc-worker/setup-doc-worker.sh            install from requirements.lock (every file pinned by sha256)
#   bash scripts/factory-v2/doc-worker/setup-doc-worker.sh --relock   regenerate requirements.lock from requirements.in
# No sudo and no system pip needed: pip itself comes from a wheel whose sha256 is checked against PyPI metadata.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEST="${FACTORY_DOC_WORKER_DIR:-$HOME/factory-v2/doc-worker}"
VENV="$DEST/venv"
PIP_VERSION="25.3"
case "$DEST" in /mnt/*) echo "refusing to use /mnt" >&2; exit 1;; esac
mkdir -p "$DEST"
if [ ! -x "$VENV/bin/python" ]; then python3 -m venv --without-pip "$VENV"; fi
if ! "$VENV/bin/python" -m pip --version >/dev/null 2>&1; then
  TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
  python3 - "$PIP_VERSION" "$TMP" <<'PY'
import hashlib, json, sys, urllib.request
version, tmp = sys.argv[1], sys.argv[2]
meta = json.load(urllib.request.urlopen(f"https://pypi.org/pypi/pip/{version}/json", timeout=60))
wheel = next(f for f in meta["urls"] if f["filename"].endswith("-py3-none-any.whl"))
data = urllib.request.urlopen(wheel["url"], timeout=120).read()
if hashlib.sha256(data).hexdigest() != wheel["digests"]["sha256"]: sys.exit("pip wheel checksum mismatch")
open(f"{tmp}/{wheel['filename']}", "wb").write(data)
PY
  WHEEL="$(ls "$TMP"/pip-*.whl)"
  "$VENV/bin/python" "$WHEEL/pip" install --no-index --find-links "$TMP" "pip==$PIP_VERSION" >/dev/null
fi
if [ "${1:-}" = "--relock" ]; then
  WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
  "$VENV/bin/python" -m pip install --quiet --upgrade --force-reinstall -r "$HERE/requirements.in" >/dev/null
  "$VENV/bin/python" -m pip freeze --exclude pip > "$WORK/freeze.txt"
  "$VENV/bin/python" -m pip download --quiet --no-deps --only-binary=:all: -d "$WORK/wheels" -r "$WORK/freeze.txt"
  python3 - "$WORK" "$HERE/requirements.lock" <<'PY'
import hashlib, os, re, sys
work, out = sys.argv[1], sys.argv[2]
pins = [l.strip() for l in open(f"{work}/freeze.txt") if "==" in l]
files = os.listdir(f"{work}/wheels")
def norm(name): return re.sub(r"[-_.]+", "-", name).lower()
lines = ["# Generated by setup-doc-worker.sh --relock. Every file is pinned by sha256; install uses --require-hashes."]
for pin in sorted(pins, key=str.lower):
    name, version = pin.split("==")
    mine = [f for f in files if norm(f.split("-")[0]) == norm(name) and f.split("-")[1] == version.replace("-", "_")]
    if not mine: sys.exit(f"no wheel found for {pin}")
    hashes = " ".join(f"--hash=sha256:{hashlib.sha256(open(f'{work}/wheels/{f}', 'rb').read()).hexdigest()}" for f in sorted(mine))
    lines.append(f"{pin} {hashes}")
open(out, "w").write("\n".join(lines) + "\n")
print(f"wrote {len(pins)} pins")
PY
fi
"$VENV/bin/python" -m pip install --quiet --require-hashes --only-binary=:all: -r "$HERE/requirements.lock"
echo "doc-worker ready: $VENV/bin/python -m markitdown"
"$VENV/bin/python" -c "import markitdown; print('markitdown', markitdown.__version__)"
